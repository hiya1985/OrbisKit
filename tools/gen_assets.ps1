# Generates src/font_data.h (anti-aliased bitmap font) and sce_sys/icon0.png.
# Run from the project root:  powershell -ExecutionPolicy Bypass -File tools\gen_assets.ps1
param([string]$Preview = "")
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

$root = Split-Path -Parent $PSScriptRoot
$FW = 16; $FH = 34; $EM = 27

# ---------- font ----------
$font = New-Object System.Drawing.Font("Consolas", $EM, [System.Drawing.FontStyle]::Bold, [System.Drawing.GraphicsUnit]::Pixel)
$fmt = [System.Drawing.StringFormat]::GenericTypographic
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("/* Auto-generated by tools/gen_assets.ps1 - do not edit */")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("#define FONT_W $FW")
[void]$sb.AppendLine("#define FONT_H $FH")
[void]$sb.AppendLine("static const unsigned char font_data[95][$($FW*$FH)] = {")

$sheet = New-Object System.Drawing.Bitmap(($FW * 32), ($FH * 3))
$gs = [System.Drawing.Graphics]::FromImage($sheet); $gs.Clear([System.Drawing.Color]::Black)

for ($c = 32; $c -le 126; $c++) {
    $bmp = New-Object System.Drawing.Bitmap($FW, $FH)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.Clear([System.Drawing.Color]::Black)
    $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAliasGridFit
    $g.DrawString([string][char]$c, $font, [System.Drawing.Brushes]::White, [single]0, [single]2, $fmt)
    $g.Dispose()
    $vals = New-Object System.Collections.Generic.List[string]
    for ($y = 0; $y -lt $FH; $y++) { for ($x = 0; $x -lt $FW; $x++) { $vals.Add([string]$bmp.GetPixel($x, $y).R) } }
    [void]$sb.AppendLine("  {" + ($vals -join ",") + "},")
    $i = $c - 32
    $gs.DrawImage($bmp, ($i % 32) * $FW, [math]::Floor($i / 32) * $FH)
    $bmp.Dispose()
}
[void]$sb.AppendLine("};")
[IO.File]::WriteAllText((Join-Path $root "src\font_data.h"), $sb.ToString())
if ($Preview) { $sheet.Save($Preview, [System.Drawing.Imaging.ImageFormat]::Png) }
$gs.Dispose(); $sheet.Dispose()

# ---------- icon ----------
New-Item -ItemType Directory -Force (Join-Path $root "sce_sys\about") | Out-Null
$icon = New-Object System.Drawing.Bitmap(512, 512)
$g = [System.Drawing.Graphics]::FromImage($icon)
$g.SmoothingMode = 'AntiAlias'; $g.TextRenderingHint = 'AntiAliasGridFit'
$rect = New-Object System.Drawing.Rectangle(0, 0, 512, 512)
$grad = New-Object System.Drawing.Drawing2D.LinearGradientBrush($rect, [System.Drawing.Color]::FromArgb(255, 20, 40, 80), [System.Drawing.Color]::FromArgb(255, 58, 123, 213), 45)
$g.FillRectangle($grad, $rect)
$big = New-Object System.Drawing.Font("Segoe UI", 150, [System.Drawing.FontStyle]::Bold, [System.Drawing.GraphicsUnit]::Pixel)
$small = New-Object System.Drawing.Font("Segoe UI", 64, [System.Drawing.FontStyle]::Bold, [System.Drawing.GraphicsUnit]::Pixel)
$center = New-Object System.Drawing.StringFormat; $center.Alignment = 'Center'
$big = New-Object System.Drawing.Font("Segoe UI", 132, [System.Drawing.FontStyle]::Bold, [System.Drawing.GraphicsUnit]::Pixel)
$g.DrawString("ORBIS", $big, [System.Drawing.Brushes]::White, (New-Object System.Drawing.RectangleF(0, 120, 512, 200)), $center)
$g.DrawString("KIT", $small, [System.Drawing.Brushes]::White, (New-Object System.Drawing.RectangleF(0, 300, 512, 100)), $center)
$g.Dispose()
$icon.Save((Join-Path $root "sce_sys\icon0.png"), [System.Drawing.Imaging.ImageFormat]::Png)
$icon.Dispose()
Write-Host "Generated src\font_data.h and sce_sys\icon0.png"
